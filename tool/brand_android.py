"""Android outputs of tool/brand_assets.py: adaptive-icon XML and legacy PNGs."""
from __future__ import annotations

from PIL import Image, ImageDraw

from brand_spec import *  # noqa: F401,F403 - constants only


def rounded(image: Image.Image) -> Image.Image:
    size = image.width
    mask = Image.new("L", (size * SUPERSAMPLE,) * 2, 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, *mask.size), radius=LEGACY_CORNER * mask.width, fill=255)
    out = image.convert("RGBA")
    out.putalpha(mask.resize((size, size), Image.LANCZOS))
    return out


def write_android_legacy(master: Image.Image) -> None:
    for density, pixels in LEGACY_DENSITIES.items():
        small = master.resize((pixels, pixels), Image.LANCZOS)
        rounded(small).save(ANDROID_RES / f"mipmap-{density}/ic_launcher.png")


def _pill(x: float, y: float, w: float, h: float, r: float) -> str:
    """A rounded rectangle as Android vector path data, in dp."""
    c = ADAPTIVE_CANVAS / 2
    px = lambda v: c + (v - MARK_CENTER[0]) * ADAPTIVE_SCALE
    py = lambda v: c + (v - MARK_CENTER[1]) * ADAPTIVE_SCALE
    r *= ADAPTIVE_SCALE
    w *= ADAPTIVE_SCALE
    h *= ADAPTIVE_SCALE
    x, y = px(x), py(y)
    return (f"M{x + r:.2f},{y:.2f}h{w - 2 * r:.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{r:.2f}"
            f"v{h - 2 * r:.2f}a{r:.2f},{r:.2f} 0 0 1 {-r:.2f},{r:.2f}h{-(w - 2 * r):.2f}"
            f"a{r:.2f},{r:.2f} 0 0 1 {-r:.2f},{-r:.2f}v{-(h - 2 * r):.2f}"
            f"a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{-r:.2f}z")


def vector(colours: list[str]) -> str:
    paths = "\n".join(
        f'    <path android:fillColor="{colour}" android:pathData="{_pill(*shape[:5])}"/>'
        for shape, colour in zip(SHAPES, colours)
    )
    size = ADAPTIVE_CANVAS
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/brand_assets.py from AppIcon.icon. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp" android:height="{size}dp"\n'
        f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n'
        f"{paths}\n</vector>\n"
    )


def write_android_adaptive() -> None:
    (ANDROID_RES / "drawable/ic_launcher_foreground.xml").write_text(
        vector([PURPLE, BLUE, TEAL]))
    (ANDROID_RES / "drawable/ic_launcher_monochrome.xml").write_text(
        vector(["#FF000000"] * 3))
    hexcolour = "#{:02X}{:02X}{:02X}".format(*BACKGROUND)
    (ANDROID_RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/brand_assets.py from AppIcon.icon. Do not edit. -->\n'
        f'<resources>\n    <color name="ic_launcher_background">{hexcolour}</color>\n'
        '</resources>\n')
    folder = ANDROID_RES / "mipmap-anydpi-v26"
    folder.mkdir(exist_ok=True)
    (folder / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/brand_assets.py from AppIcon.icon. Do not edit. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
        '</adaptive-icon>\n')
